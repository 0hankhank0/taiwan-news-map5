const assert = require('node:assert/strict');
const path = require('node:path');
process.env.EVENT_STORE_MODE = 'local';
process.env.EVENT_DB_PATH = path.join(require('node:os').tmpdir(), `review-regressions-${process.pid}-${Date.now()}.sqlite`);
delete process.env.KV_REST_API_URL;
delete process.env.KV_REST_API_TOKEN;
const refresh = require('../event-refresh');
const normalizer = require('../event-normalizer');
const store = require('../event-store');
const submissions = require('../submission-store');
const now = Date.now();
const iso = h => new Date(now + h * 3600000).toISOString();
const base = {category:'activity', eventKind:'activity', city:'台北市', lat:25.033, lng:121.565, source:'iculture', startsAt:iso(1), endsAt:iso(3), expiresAt:now+9*3600000, createdAt:now};
async function main(){
  const a = {...base,id:'a',title:'台北攝影展',venue:'台北藝文館'};
  const b = {...base,id:'b',title:'高雄音樂祭',venue:'高雄文化中心',city:'高雄市',lat:22.63,lng:120.30};
  assert.notEqual(refresh.activityOccurrenceKey(a),refresh.activityOccurrenceKey(b));
  assert.equal(refresh.mergeRefreshEvents([], [a,b],now).length,2);
  console.log('regression check passed');
  const sessions = [{...a,id:'session-1'}, {...a,id:'session-2',startsAt:iso(25),endsAt:iso(27),expiresAt:now+33*3600000}];
  assert.equal(refresh.mergeRefreshEvents([],sessions,now).length,2);
  assert.equal(normalizer.normalizeEventsForFrontend(sessions).length,2);
  const normalized = normalizer.normalizeEventsForFrontend(sessions);
  assert.deepEqual(new Set(normalized.map(event => event.id)), new Set(['session-1', 'session-2']));
  assert.ok(normalized.every(event => event.title === a.title));
  const exactSessions = sessions.map(event => ({ ...event, locationSource: 'manual', locationPrecision: 'exact', locationQuality: 'high' }));
  assert.equal(normalizer.normalizeEventsForFrontend(exactSessions).length, 2);
  assert.equal(normalizer.normalizeEventsForFrontend([exactSessions[0], { ...exactSessions[0], id: 'same-session' }]).length, 1);
  console.log('activity sessions and fallback location metadata preserved');
  const s = await submissions.createSubmission({title:'信義路交通事故',description:'信義路交通事故，車道暫時封閉，請用路人注意安全。',category:'traffic',latitude:25.033,longitude:121.565,sourceUrl:'https://news.test/item'});
  await submissions.updateSubmission(s.submissionId,{status:'approved'});
  const saved = await store.updateOfficialEvent(`submission:${s.submissionId}`,{title:'管理員已修正標題',status:'resolved'});
  const reread = (await store.getOfficialEvents()).find(e=>e.submissionId===s.submissionId);
  assert.equal(saved.title,'管理員已修正標題');
  assert.equal(reread.title,saved.title);
  assert.equal(reread.status,'resolved');
  await submissions.updateSubmission(s.submissionId,{status:'rejected'});
  assert.equal((await store.getOfficialEvents()).some(e=>e.submissionId===s.submissionId),false);
  console.log('regression check passed');
  const current = {id:'pbs-review',title:'台北道路事故',content:'車道封閉',category:'traffic',eventKind:'incident',source:'pbs',lat:25.033,lng:121.565,city:'台北市',createdAt:now,publishedAt:iso(-1),expiresAt:now+3600000,status:'resolved',statusSource:'manual',categorySource:'manual',reviewState:'reviewed'};
  const incoming = {...current,status:'active',statusSource:'pbs',categorySource:'official',reviewState:'unreviewed'};
  const result = await refresh.runEventRefresh({mode:'news',write:false,skipExternalGeocoding:true,now,existingEvents:[current],sourceData:{pbsEvents:[incoming],__collectorResults:{pbs:{status:'success'}}}});
  const row = result.events.find(e=>e.id===current.id);
  assert.equal(row.status,'resolved');
  assert.equal(row.categorySource,'manual');
  console.log('regression check passed');
}
main().catch(e=>{console.error(e);process.exitCode=1});
